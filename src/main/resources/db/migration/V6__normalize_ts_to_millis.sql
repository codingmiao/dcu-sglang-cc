-- V6：把 request_stat.ts 从"秒"归一化成"毫秒"。
-- 背景：早期构建曾把 ts 写成秒（~1.7e9），而趋势图按毫秒分桶
-- （(ts / 桶毫秒) * 桶毫秒），单位错配会让近 7 天 / 30 天的所有行塌进同一个桶，
-- 图上只剩一根柱子。
-- 判据：1e11 是分界——1e11 毫秒 = 1973 年，1e11 秒 = 5138 年，
-- 所以 ts < 1e11 的一定是秒，乘 1000 归一化；已是毫秒的行（>= 1e11）不受影响。
-- 幂等：归一化后这些行变成毫秒（>= 1e11），再跑也不会被命中。
UPDATE request_stat SET ts = ts * 1000 WHERE ts < 100000000000;
